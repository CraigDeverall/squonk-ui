import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { StdioClientTransport } from "@modelcontextprotocol/sdk/client/stdio.js";
// Drives the built server like an agent would: lookups, story listing, an
// unknown story, and two stories with screenshots. Usage: node test/e2e.mjs [app root] [png path]
import { writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
const root = process.argv[2] ?? new URL("../../..", import.meta.url).pathname;
const out = process.argv[3] ?? path.join(tmpdir(), "squonk-ui-preview.png");
const client = new Client({ name: "e2e", version: "0" });
await client.connect(new StdioClientTransport({ command: "node", args: [new URL("../dist/cli.js", import.meta.url).pathname, "--root", root] }));
const toolList = await client.listTools();
console.log(toolList.tools.map((t) => t.name + (t._meta?.ui ? " (ui)" : "")).join(", "));
const find = await client.callTool({ name: "find_components", arguments: { query: "confirm dialog" } });
console.log(find.content[0].text.slice(0, 400));
const tools = toolList.tools.map((t) => t.name);
if (tools.includes("preview")) throw new Error("the composition preview tool is gone");
const listed = JSON.parse((await client.callTool({ name: "list_stories", arguments: { query: "searchable select" } })).content[0].text);
if (listed.stories[0]?.id !== "functional-select--searchable") throw new Error(`list_stories ranked ${listed.stories[0]?.id} first`);
const navList = JSON.parse((await client.callTool({ name: "list_stories", arguments: { component: "NavList" } })).content[0].text);
if (!navList.stories.length || !navList.stories.every((s) => s.component === "nav-list")) throw new Error("list_stories didn't filter by component");
const demos = JSON.parse((await client.callTool({ name: "list_stories", arguments: { query: "member dashboard" } })).content[0].text);
if (demos.stories[0]?.kind !== "demo") throw new Error("list_stories doesn't find the example screens");
console.log("list_stories:", listed.total, "match 'searchable select';", navList.total, "NavList stories; first demo", demos.stories[0].id);
const bad = await client.callTool({ name: "preview_story", arguments: { storyId: "functional-buton--primary" } });
if (!bad.isError || !bad.content[0].text.includes("functional-button--primary")) throw new Error("an unknown story should fail with close matches");
console.log("bad:", bad.content[0].text.slice(0, 200));
const good = await client.callTool({ name: "preview_story", arguments: { storyId: "functional-button--primary", width: 420, screenshot: true } });
console.log("good:", good.isError, good.content[0].text);
if (good.isError || !good.content[0].text.includes("rendered without errors")) throw new Error("the Button story didn't render");
const img = good.content.find((c) => c.type === "image");
if (img) writeFileSync(out, Buffer.from(img.data, "base64"));
const dark = await client.callTool({ name: "preview_story", arguments: { storyId: demos.stories[0].id, theme: "dark", width: 1280, screenshot: true } });
console.log("demo:", dark.isError, dark.content[0].text);
if (dark.isError || !dark.content[0].text.includes("rendered without errors")) throw new Error("the demo didn't render");
const img2 = dark.content.find((c) => c.type === "image");
if (img2) writeFileSync(out.replace(".png", "-dark.png"), Buffer.from(img2.data, "base64"));
// The catalog is a resource too: the whole thing, and one entry per component.
const whole = JSON.parse((await client.readResource({ uri: "squonk-ui://catalog" })).contents[0].text);
if (!whole.components?.some((c) => c.id === "button")) throw new Error("catalog resource lacks Button");
const resources = (await client.listResources()).resources.map((r) => r.uri);
if (!resources.includes("squonk-ui://catalog") || !resources.includes("squonk-ui://components/button")) throw new Error(`resources missing: ${resources.slice(0, 5)}`);
const button = JSON.parse((await client.readResource({ uri: "squonk-ui://components/button" })).contents[0].text);
if (button.id !== "button") throw new Error("component resource returned the wrong entry");
console.log("catalog resources:", whole.components.length, "components,", resources.length, "resources listed");
// The design guides: searchable, readable, and linked from each component's patterns.
const found = JSON.parse((await client.callTool({ name: "find_guidance", arguments: { query: "badge or tag" } })).content[0].text);
if (found[0]?.id !== "patterns-labels-badge-or-tag") throw new Error(`find_guidance ranked ${found[0]?.id} first`);
const rule = (await client.callTool({ name: "get_guide", arguments: { id: "Labels: Badge or Tag" } })).content[0].text;
if (!rule.includes("A Badge reports. A Tag names.")) throw new Error("get_guide lost the rule");
const colour = (await client.readResource({ uri: "squonk-ui://guides/foundations-colour" })).contents[0];
if (colour.mimeType !== "text/markdown" || !colour.text.includes("--squonk-roles-color-accent")) throw new Error("guide resource is wrong");
if (!resources.includes("squonk-ui://guides") || !resources.includes("squonk-ui://guides/patterns-forms-the-basics")) throw new Error("guides are not listed as resources");
const textField = JSON.parse((await client.callTool({ name: "get_component", arguments: { id: "text-field" } })).content[0].text);
if (!textField.patterns?.some((p) => p.guide?.startsWith("squonk-ui://guides/"))) throw new Error("component patterns lack guide links");
console.log("guides:", found.length, "match 'badge or tag'; first", found[0].id);
const res = await client.readResource({ uri: "ui://squonk-ui/story" });
console.log("resource", res.contents[0].mimeType, Math.round(res.contents[0].text.length / 1024), "KB");
console.log("screenshots:", out);
await client.close();
